import { ChevronRightIcon, InfoIcon } from "lucide-react";
import { T, useGT } from "gt-react";
import { useState, type KeyboardEvent } from "react";

import { cn } from "~/lib/utils";
import { WorkLogDetails, WorkLogRow } from "../chat/WorkLog";

/** The environment an imported session's agent generated, collapsed and shown as plain text. */
export function ImportedEnvironmentRow(props: { readonly environment: string }) {
  const gt = useGT();
  const [expanded, setExpanded] = useState(false);
  const toggle = () => setExpanded((open) => !open);
  return (
    <WorkLogRow
      data-v2-item-type="system_notice"
      onClick={toggle}
      toggle={{
        role: "button",
        tabIndex: 0,
        "aria-expanded": expanded,
        onKeyDown: (event: KeyboardEvent<HTMLDivElement>) => {
          if (
            event.target === event.currentTarget &&
            (event.key === "Enter" || event.key === " ")
          ) {
            event.preventDefault();
            toggle();
          }
        },
      }}
      icon={<InfoIcon aria-hidden className="size-4 shrink-0 text-icon-muted" />}
      label={
        <span className="truncate text-sm text-foreground/80">
          {gt("Original session environment")}
        </span>
      }
      trailing={
        <span className="flex size-4 shrink-0 items-center justify-center" aria-hidden>
          <ChevronRightIcon
            className={cn(
              "size-3 shrink-0 text-icon-muted opacity-70 transition-transform duration-200",
              expanded && "rotate-90",
            )}
          />
        </span>
      }
    >
      {expanded ? (
        <WorkLogDetails>
          <p className="text-sm text-muted-foreground">
            <T>
              Generated by the agent in the imported session. These values describe that session,
              not this one.
            </T>
          </p>
          <pre className="whitespace-pre-wrap break-words font-mono text-xs text-foreground/80">
            {props.environment}
          </pre>
        </WorkLogDetails>
      ) : null}
    </WorkLogRow>
  );
}
